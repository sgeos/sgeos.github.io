#!/usr/bin/env python3
"""The Equations section, an index of every display equation in a post, classified.

    python3 _lib/equations.py check POST         # drift between the body, the data and the section
    python3 _lib/equations.py unfold POST [--write] # rewrite single-line `$$...$$` as `$$` blocks
    python3 _lib/equations.py tag POST [--write] # number the body equations with \\tag{n}
    python3 _lib/equations.py write POST         # regenerate the section from the data file
    python3 _lib/equations.py stamp POST         # record the current digest of every equation
    python3 _lib/equations.py skeleton POST      # print a data file to fill in, for a new post

WHAT THE SECTION IS. A post with many display equations gets an `## Equations`
section immediately before `## References`. It lists every display equation in
the order it appears, under the number it carries in the body, with a title, a
one-sentence gloss and the equation reproduced character for character. The
section opens with a caution on units and ends with a notation key.

STANDARD AND BESPOKE. Each equation is classified as one or the other. A
standard equation is an established result formalised without addition, and
usually carries a citation. A bespoke equation is a construction made for the
analysis, such as a budget assembled from standard terms, a model that a
simplifying assumption defines, or a figure of merit the article introduces.
The classification is a reader's warning about where to look for an error. A
mistake in a standard equation is a transcription error that a textbook can
settle, while a bespoke equation can be wrong in its construction, and only the
article's own argument supports it. Bold titles mark standard equations, and
italic titles beginning with the word Bespoke mark bespoke ones, so the
distinction survives without colour or icons.

THE BODY GOVERNS. The section is generated, never edited by hand. The equations
are copied out of the body each time, so the index cannot reproduce an equation
the body no longer contains. What can go stale is the human judgement in the
data file, a title, a class or a gloss written for an equation that has since
changed. Each data entry therefore records a digest of the equation it was
written for, and `check` fails when the body equation no longer matches it. The
digest is SHA-256 used only to detect change and carries no security meaning.
After reviewing an entry against the changed equation, `stamp` records the new
digest.

WHAT CHECK ENFORCES, each a way a hand-maintained index can drift.
  - Every body equation carries `\\tag{n}`, numbered 1 to N in order.
  - Every body equation has exactly one data entry, and no entry lacks one.
  - Every entry's digest matches its equation.
  - Every cited anchor is already cited in the body, which keeps the generated
    References unchanged and the citation's label consistent with the body.
  - Every notation symbol appears in at least one equation, so a key entry for
    a symbol the article dropped is caught.
  - The section on disk equals what `write` would produce.

MATHJAX. The site configures no automatic numbering, and an explicit `\\tag{n}`
renders under that configuration. The index repeats each tag, which is harmless
because no equation carries a `\\label`, so no reference can become ambiguous.

DATA. `_sources/equations/<article>.toml`, named by the article number in the
post's `<!-- Axxx -->` comment, as `_sources/decisions/` is.
"""

import hashlib
import os
import re
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import post  # noqa: E402

ROOT = os.path.dirname(HERE)
DATA_DIR = os.path.join(ROOT, "_sources", "equations")

HEADING = "## Equations"
MARKER = ("<!-- Equations generated by _lib/equations.py from _sources/equations/. "
          "Edit the data file and regenerate. Do not edit this section by hand. -->")
CLASSES = ("standard", "bespoke")
ARTICLE = re.compile(r"(?m)^<!-- (A\d+) -->$")
TAG = re.compile(r"\\tag\{([^{}]*)\}")
TAG_LINE = re.compile(r"^\\tag\{[^{}]*\}$")
REQUIRED = ("tag", "class", "title", "gloss", "digest")
OPTIONAL = ("cite",)


class EquationError(ValueError):
    pass


def article_number(text):
    found = ARTICLE.findall(text)
    if len(found) != 1:
        raise EquationError(f"expected one <!-- Axxx --> comment, found {len(found)}")
    return found[0]


def data_path(text):
    return os.path.join(DATA_DIR, article_number(text) + ".toml")


def load(path):
    with open(path, "rb") as fh:
        data = tomllib.load(fh)
    validate(data)
    return data


def validate(data):
    """Shape of a data file. Every failure is collected, so one run fixes the file."""
    problems = []
    if not isinstance(data.get("caution"), str) or not data["caution"].strip():
        problems.append("`caution` must be a non-empty string")
    entries = data.get("equation")
    if not isinstance(entries, list) or not entries:
        problems.append("at least one [[equation]] is required")
        entries = []
    for i, e in enumerate(entries, 1):
        where = f"[[equation]] {i}"
        for k in REQUIRED:
            if k not in e:
                problems.append(f"{where}: missing `{k}`")
        for k in e:
            if k not in REQUIRED + OPTIONAL:
                problems.append(f"{where}: unknown key `{k}`")
        if "tag" in e and (not isinstance(e["tag"], int) or isinstance(e["tag"], bool) or e["tag"] < 1):
            problems.append(f"{where}: `tag` must be a positive integer")
        if e.get("class") not in CLASSES and "class" in e:
            problems.append(f"{where}: `class` must be one of {CLASSES}")
        if e.get("class") == "bespoke" and not str(e.get("title", "")).startswith("Bespoke "):
            problems.append(f"{where}: a bespoke title must begin with `Bespoke `")
        if e.get("class") == "standard" and str(e.get("title", "")).startswith("Bespoke"):
            problems.append(f"{where}: a standard title must not begin with `Bespoke`")
        for k in ("title", "gloss", "digest"):
            if k in e and (not isinstance(e[k], str) or not e[k].strip() or "\n" in e[k]):
                problems.append(f"{where}: `{k}` must be a non-empty single-line string")
        if "cite" in e and (not isinstance(e["cite"], list)
                            or not all(isinstance(a, str) and re.fullmatch(post.ANCHOR, a) for a in e["cite"])):
            problems.append(f"{where}: `cite` must be a list of anchors")
    tags = [e.get("tag") for e in entries]
    if tags != list(range(1, len(entries) + 1)):
        problems.append(f"entries must be tagged 1 to {len(entries)} in order, found {tags}")
    symbols = data.get("symbol", [])
    if not isinstance(symbols, list):
        problems.append("`symbol` must be an array of tables")
        symbols = []
    for i, s in enumerate(symbols, 1):
        if set(s) != {"tex", "meaning"} or not all(isinstance(v, str) and v.strip() for v in s.values()):
            problems.append(f"[[symbol]] {i}: needs exactly `tex` and `meaning`, both non-empty strings")
    if problems:
        raise EquationError("; ".join(problems))


def split_section(text):
    """(before, section, after) around an existing Equations section.

    The section runs from its heading to `## References`, so it is part of the
    body as `post.split` sees it and its citations count as uses. A post with
    no section yields an empty middle and `before` ending at the references.
    """
    front, body, refs = post.split(text)
    if not refs:
        raise EquationError("no `## References` heading to place the section before")
    head = "\n" + HEADING + "\n"
    if head in body:
        before, section = body.split(head, 1)
        return front + before + "\n", HEADING + "\n" + section, refs
    return front + body, "", refs


def blocks(text):
    """Display equations of the body outside the Equations section, as (line, latex).

    Only the two forms the corpus uses are recognised, a `$$` line opening and
    another closing a block, and a whole line `$$...$$`. Anything else holding
    `$$` is left to `_verify.py`, which already fails a display equation sharing
    a line with prose. Line numbers count from the top of the file.
    """
    before = split_section(text)[0]
    raw = before.split("\n")
    lines = post.strip_code_keeping_lines(before).split("\n")
    out = []
    i = 0
    while i < len(lines):
        line = lines[i]
        one = re.fullmatch(r"\$\$(.+)\$\$", line)
        if one:
            out.append((i + 1, raw[i][2:-2]))
        elif line == "$$":
            j = i + 1
            while j < len(lines) and lines[j] != "$$":
                j += 1
            if j == len(lines):
                raise EquationError(f"line {i + 1}: display equation never closes")
            out.append((i + 1, "\n".join(raw[i + 1:j])))
            i = j
        i += 1
    return out


def unseparated(text):
    """Line numbers of display equations that touch a non-blank line above or below.

    Kramdown reads such a block as part of the adjoining paragraph and renders it
    as inline math, so the reader sees an equation run into the prose. Its
    `\\tag` is then a MathJax error, because a tag is not allowed in inline math.
    The delimiters balance and the markup resolves, so `render.py` cannot see it.
    """
    before = split_section(text)[0]
    lines = post.strip_code_keeping_lines(before).split("\n")
    out = []
    for line, latex in blocks(text):
        first = line - 1
        last = first if re.fullmatch(r"\$\$(.+)\$\$", lines[first]) else first + latex.count("\n") + 2
        if (first > 0 and lines[first - 1].strip()) or (last + 1 < len(lines) and lines[last + 1].strip()):
            out.append(line)
    return out


def untagged(latex):
    """The equation without its tag line, which is what a digest describes."""
    return "\n".join(l for l in latex.split("\n") if not TAG_LINE.match(l))


def digest(latex):
    return hashlib.sha256(untagged(latex).encode("utf-8")).hexdigest()[:16]


def body_labels(text):
    """{anchor: label} for the first `[label][anchor]` of each anchor in the body.

    Link text may be wrapped over several source lines, as reflowed prose often
    is, so the label may span line breaks and is rejoined with single spaces.
    """
    body = post.strip_code(split_section(text)[0])
    out = {}
    for label, anchor in re.findall(rf"\[([^\[\]]+)\]\[({post.ANCHOR})\]", post.strip_math(body)):
        out.setdefault(anchor, " ".join(label.split()))
    return out


def render(text, data):
    """The Equations section for a post, from its body and its data file."""
    eqs = blocks(text)
    labels = body_labels(text)
    entries = data["equation"]
    n_std = sum(1 for e in entries if e["class"] == "standard")
    lines = [HEADING, "", MARKER, "",
             f"This section collects the {len(eqs)} display equations of the article in the order they appear,",
             "each under its number and reproduced exactly as it stands in the text.",
             "A title in bold names an established result,",
             "and a title in italics beginning with the word Bespoke names a construction made for this analysis.",
             f"Of the {len(eqs)}, {n_std} are established and {len(eqs) - n_std} are bespoke.",
             data["caution"].strip(), ""]
    for e, (_line, latex) in zip(entries, eqs):
        mark = "**" if e["class"] == "standard" else "*"
        lines.append(f"{mark}Equation {e['tag']}, {e['title']}.{mark}")
        lines.append(e["gloss"].strip())
        for a in e.get("cite", []):
            lines.append(f"[{labels[a]}][{a}]")
        lines += ["", "$$", latex, "$$", ""]
    symbols = data.get("symbol", [])
    if symbols:
        lines += ["### Notation", ""]
        lines += [f"- ${s['tex']}$, {s['meaning'].strip()}" for s in symbols]
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def check(text, data, section=True):
    """Every way the body, the data and the section disagree. Empty means consistent.

    `section=False` skips the comparison with the section on disk, which is what
    `write` needs before it replaces that section.
    """
    problems = []
    try:
        eqs = blocks(text)
    except EquationError as e:
        return [str(e)]
    for n, (line, latex) in enumerate(eqs, 1):
        tags = TAG.findall(latex)
        if tags != [str(n)]:
            problems.append(f"line {line}: equation {n} carries tags {tags}, expected [{str(n)!r}]")
    for line in unseparated(text):
        problems.append(f"line {line}: display equation touches the text beside it; "
                        f"add a blank line, or it renders as inline math")
    entries = data["equation"]
    if len(entries) != len(eqs):
        problems.append(f"the body has {len(eqs)} display equations and the data file {len(entries)} entries")
    for e, (line, latex) in zip(entries, eqs):
        if e["digest"] != digest(latex):
            problems.append(f"line {line}: equation {e['tag']} changed since it was classified; "
                            f"review its entry, then stamp (now {digest(latex)})")
    labels = body_labels(text)
    for e in entries:
        for a in e.get("cite", []):
            if a not in labels:
                problems.append(f"equation {e['tag']} cites [{a}], which the body never cites")
    every = "\n".join(latex for _l, latex in eqs)
    for s in data.get("symbol", []):
        if s["tex"] not in every:
            problems.append(f"notation symbol {s['tex']!r} appears in no equation")
    if problems or not section:
        return problems
    if split_section(text)[1] != render(text, data) + "\n":
        problems.append("the Equations section differs from what `write` produces; regenerate it")
    return problems


def check_article(path, text=None):
    """Problems for a post with an Equations section or a data file, and none for any other.

    The gate entry point. A post that has neither is outside this convention and
    passes untouched, so adopting it is per article. Having one without the
    other is a defect in both directions, since a section without data cannot be
    regenerated and data without a section means a `write` was never run. The
    gate passes `text` because it has already read the post, and its tests check
    posts that exist only in memory.
    """
    if text is None:
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
    has_section = ("\n" + HEADING + "\n") in text
    try:
        dpath = data_path(text)
    except EquationError as e:
        return [f"an Equations section, but {e}"] if has_section else []
    if not os.path.exists(dpath):
        return [f"an Equations section with no {os.path.relpath(dpath, ROOT)}"] if has_section else []
    try:
        data = load(dpath)
    except (EquationError, OSError, tomllib.TOMLDecodeError) as e:
        return [f"{os.path.relpath(dpath, ROOT)}: {e}"]
    if not has_section:
        return [f"{os.path.relpath(dpath, ROOT)} exists and the post has no Equations section; run write"]
    return check(text, data)


def unfolded(text):
    """The post with every single-line body equation rewritten as a `$$` block.

    Tagging needs the block form, because the tag goes on a line of its own. The
    rewrite moves line breaks only, so the equation's text and its digest are
    unchanged and the rendered mathematics is the same. An equation that already
    carries a tag on its one line is refused, since splitting the tag out is a
    judgement about where the equation ends.
    """
    lines = text.split("\n")
    for line, latex in reversed(blocks(text)):
        start = line - 1
        if lines[start] == "$$":
            continue
        if TAG.search(latex):
            raise EquationError(f"line {line}: a single-line equation already carries a tag")
        lines[start:start + 1] = ["$$", latex, "$$"]
    return "\n".join(lines)


def tagged(text):
    """The post with every body equation numbered in order, replacing old tags."""
    eqs = blocks(text)
    lines = text.split("\n")
    for n, (line, latex) in reversed(list(enumerate(eqs, 1))):
        start = line - 1
        if lines[start] != "$$":
            raise EquationError(f"line {line}: write a single-line equation as a `$$` block before tagging")
        end = start + 1 + len(latex.split("\n"))
        inner = [l for l in lines[start + 1:end] if not TAG_LINE.match(l)]
        if TAG.search("\n".join(inner)):
            raise EquationError(f"line {line}: a tag inside an equation line; move it to its own line")
        lines[start + 1:end] = inner + [f"\\tag{{{n}}}"]
    return "\n".join(lines)


def written(text, data):
    before, _old, refs = split_section(text)
    return before + render(text, data) + "\n" + refs


def stamped(path, text):
    """The data file text with each entry's digest replaced by its equation's current one."""
    with open(path, encoding="utf-8") as fh:
        src = fh.read()
    eqs = blocks(text)
    parts = re.split(r"(?m)^(?=\[\[equation\]\]\s*$)", src)
    if len(parts) - 1 != len(eqs):
        raise EquationError(f"the data file has {len(parts) - 1} entries and the body {len(eqs)} equations")
    for k in range(1, len(parts)):
        new, n = re.subn(r'(?m)^digest = "[^"]*"$', f'digest = "{digest(eqs[k - 1][1])}"', parts[k])
        if n != 1:
            raise EquationError(f"[[equation]] {k}: expected one `digest = \"...\"` line, found {n}")
        parts[k] = new
    return "".join(parts)


def skeleton(text):
    rows = [f'# Equation classification for {article_number(text)}. Read by `python3 _lib/equations.py`.',
            "", 'caution = ""', ""]
    for n, (line, latex) in enumerate(blocks(text), 1):
        first = untagged(latex).split("\n")[0][:70]
        rows += ["[[equation]]", f"# line {line}: {first}", f"tag = {n}", 'class = ""',
                 'title = ""', 'gloss = ""', "cite = []", f'digest = "{digest(latex)}"', ""]
    return "\n".join(rows)


def _write(path, text):
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def main(argv):
    args = argv[1:]
    usage = "usage: equations.py {check|unfold|tag|write|stamp|skeleton} POST [--write]"
    if len(args) < 2 or args[0] not in ("check", "unfold", "tag", "write", "stamp", "skeleton"):
        print(usage)
        return 2
    cmd, path = args[0], args[1]
    try:
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
        if cmd == "skeleton":
            print(skeleton(text))
            return 0
        if cmd == "unfold":
            out = unfolded(text)
            n = len(out.split("\n")) - len(text.split("\n"))
            if "--write" in args and out != text:
                _write(path, out)
            print(f"{'unfolded' if '--write' in args else 'would unfold'} {n // 2} equation(s) in {path}")
            return 0
        if cmd == "tag":
            out = tagged(text)
            if "--write" in args and out != text:
                _write(path, out)
            print(f"{'tagged' if '--write' in args else 'would tag'} {len(blocks(text))} equation(s) in {path}"
                  + ("" if out != text else ", already tagged"))
            return 0
        dpath = data_path(text)
        if cmd == "stamp":
            _write(dpath, stamped(dpath, text))
            load(dpath)
            print(f"stamped {dpath}")
            return 0
        data = load(dpath)
        if cmd == "write":
            problems = check(text, data, section=False)
            if problems:
                print("\n".join(f"  {p}" for p in problems))
                print("not written; resolve the problems above first")
                return 1
            _write(path, written(text, data))
            print(f"wrote the Equations section of {path}")
            return 0
        problems = check(text, data)
        print("\n".join(f"  {p}" for p in problems) if problems
              else f"{path}: {len(data['equation'])} equations consistent")
        return 1 if problems else 0
    except (EquationError, OSError, tomllib.TOMLDecodeError) as e:
        print(f"{path}: {e}")
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
