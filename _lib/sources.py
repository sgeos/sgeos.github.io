def _front_matter(path):
    text = open(path, encoding="utf-8").read()
    m = post.FRONT_MATTER.match(text)
    if not m:
        raise SourceError(f"{path}: no front matter")
    fm = m.group(1)

    def field(k):
        mm = re.search(rf"^{k}:\s*(.*)$", fm, re.M)
        return mm.group(1).strip() if mm else ""
    title = field("title")
    if len(title) >= 2 and title[0] == title[-1] and title[0] in "\"'":
        title = title[1:-1]
    cats = field("categories")
    cats = [c.strip().strip("\"'") for c in cats.strip("[]").split(",")] if cats.startswith("[") else cats.split()
    return {"title": title, "date": field("date")[:10], "categories": [c for c in cats if c]}


def site_meta():
    cfg = open(os.path.join(ROOT, "_config.yml"), encoding="utf-8").read()

    def field(k):
        m = re.search(rf"^{k}:\s*(.*?)\s*(#.*)?$", cfg, re.M)
        return m.group(1).strip().strip("\"'") if m else ""
    return {"title": field("title"), "author": field("author"), "url": field("url").rstrip("/")}


def related_post_fields(r, posts_dir=POSTS):
    stem = r["post"]
    path = os.path.join(posts_dir, stem + ".markdown")
    if not os.path.exists(path):
        raise SourceError(f"{r['anchor']}: related post {stem} is not in _posts")
    fm = _front_matter(path)
    if fm["date"] != stem[:10]:
        raise SourceError(f"{r['anchor']}: {stem} front matter date {fm['date']} disagrees with its filename")
    meta = site_meta()
    y, mo, d = stem[:4], stem[5:7], stem[8:10]
    # Jekyll's default permalink, /:categories/:year/:month/:day/:title.html.
    url = meta["url"] + "/" + "/".join(fm["categories"] + [y, mo, d, stem[11:] + ".html"])
    names = meta["author"].split()
    return {"title": fm["title"], "date": fm["date"], "url": url, "blog": meta["title"],
            "author": {"family": names[-1], "given": " ".join(names[:-1])}}


