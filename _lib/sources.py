#!/usr/bin/env python3
"""The source database, and the References sections generated from it.

WHY THIS EXISTS. References were typed by hand, per article, by a per-article
scratch generator. The corpus measured 415,869 link definitions on 2026-10-24,
with 14,194 anchors pointing at more than one URL and 14,634 URLs carried under
more than one anchor. The same source was described differently in different
articles, and correcting a description meant finding every copy. Here each
source is one record, and every article's References section is GENERATED from
the records it cites, so a correction is made once and a hand edit is caught.

THE SPECIFICATION IS `_docs/writing/CITATION_STYLE.md`. This module implements
it. Where the two disagree, the document is the intent and this module is the
defect.

STORAGE. `_sources/records/*.jsonl` holds one JSON object per line, sorted by
anchor and sharded by the first character of the anchor's identity, meaning the
anchor with any legacy prefix removed. `_sources/venues.jsonl` records whether a
venue referees full papers. Jekyll copies no underscore directory, so none of
this is published as a page, but the repository is public and so is the data.

TRUST BOUNDARY. Records hold text from Crossref, Wikipedia and other registries,
all untrusted. Every string written into Markdown passes through `md_escape`,
which neutralises the characters that would open a link, emphasis, code span,
inline HTML, Liquid tag or MathJax delimiter. A title can change what the entry
says but cannot change how the page around it parses.

Stdlib only, like `_verify.py`, which imports this module and must run on a bare
CI runner.

Usage:
    python3 _lib/sources.py validate
    python3 _lib/sources.py render POST      # print the generated section
    python3 _lib/sources.py write POST       # replace the section in place
    python3 _lib/sources.py check POST...    # exit nonzero on any drift
    python3 _lib/sources.py fix-labels POST  # set in-text labels to the database's
    python3 _lib/sources.py diff-labels PRE POST  # review what a conversion changed
"""

import datetime
import glob
import json
import os
import re
import sys
import unicodedata

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import post  # noqa: E402  the one module that knows how a post is laid out

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STORE = os.path.join(ROOT, "_sources")
RECORDS = os.path.join(STORE, "records")
VENUES = os.path.join(STORE, "venues.jsonl")
ARTICLES = os.path.join(STORE, "articles")
POSTS = os.path.join(ROOT, "_posts")

MARKER = ("<!-- References generated by _lib/sources.py from _sources/. "
          "Edit the database and regenerate. Do not edit this section by hand. -->")

# Display order, which is the reliability ranking. See CITATION_STYLE.md.
SECTIONS = (
    "Primary Sources, Peer-Reviewed",
    "Primary Sources, Non-Peer-Reviewed",
    "Secondary Sources",
    "Commercial Sources",
    "General Sources",
    "Tertiary Sources",
    "Related Posts",
)

# Rule number to the sections it may place a source in. Rule 3 has two, because
# a review article in a refereed venue is secondary.
RULE_SECTIONS = {
    1: {"Related Posts"},
    2: {"Tertiary Sources"},
    3: {"Primary Sources, Peer-Reviewed", "Secondary Sources"},
    4: {"Primary Sources, Non-Peer-Reviewed"},
    5: {"Secondary Sources"},
    6: {"Commercial Sources"},
    7: {"General Sources"},
}

KINDS = {
    "journal-article", "proceedings-paper", "abstract", "book", "chapter",
    "report", "preprint", "web-page", "wikipedia", "related-post",
    "thesis", "dataset", "standard", "documentation", "other",
}

# Legacy anchor prefixes. They carry no meaning in the new scheme and are
# stripped only to choose a shard, so shards stay balanced across prefixes.
LEGACY_PREFIXES = ("related_post_", "research_", "future_", "book_", "ref_")

# Canonical anchors in the database are stricter than what a post may contain,
# lower case only, so two spellings of one source cannot coexist.
ANCHOR_RE = re.compile(r"^[a-z0-9_]+$")
FRAGMENT_RE = re.compile(rf"^{post.ANCHOR}$")

MONTHS = ("January", "February", "March", "April", "May", "June", "July",
          "August", "September", "October", "November", "December")


class SourceError(ValueError):
    """A record, venue or article that violates the specification."""


# ----------------------------------------------------------------- storage

def shard_of(anchor):
    ident = anchor
    for p in LEGACY_PREFIXES:
        if ident.startswith(p):
            ident = ident[len(p):]
            break
    # AN ANCHOR WHOSE NAME PART IS EMPTY, `research__2026`, was generated by the
    # X-Planes harvest for authors whose names are not in Latin script. It is
    # published and kept, and sharded by its first letter or digit.
    c = ident.lstrip("_")[:1]
    if not c or not c.isalnum():
        raise SourceError(f"anchor {anchor!r} has no identity after its prefix")
    return c


def _read_jsonl(path):
    out = []
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            if line.strip():
                try:
                    out.append(json.loads(line))
                except json.JSONDecodeError as e:
                    raise SourceError(f"{path}:{n}: {e}") from e
    return out


def _dump(obj):
    return json.dumps(obj, ensure_ascii=False, sort_keys=True)


def load_venues(path=VENUES):
    if not os.path.exists(path):
        return {}
    venues = {}
    for v in _read_jsonl(path):
        if v["venue"] in venues:
            raise SourceError(f"venue {v['venue']!r} recorded twice")
        venues[v["venue"]] = v
    return venues


def load_records(directory=RECORDS):
    """Records keyed by canonical anchor, plus an index from every alias and locator."""
    records = {}
    for path in sorted(glob.glob(os.path.join(directory, "*.jsonl"))):
        for r in _read_jsonl(path):
            a = r.get("anchor")
            if a in records:
                raise SourceError(f"anchor {a!r} recorded twice")
            if shard_of(a) != os.path.basename(path)[:-6]:
                raise SourceError(f"anchor {a!r} is in shard {path}, expected {shard_of(a)}.jsonl")
            records[a] = r
    return records


# ------------------------------------------------------------ article name maps
#
# WHY. An article keeps the reference names it was written with, which the
# pilot ruled, and the corpus uses one name for different works and different
# names for one work: 14,194 anchors point at more than one URL and 14,634 URLs
# carry more than one anchor. The store therefore names each source once, its
# canonical anchor, and each article that names a source differently carries a
# map in `_sources/articles/<post stem>.json` from its own names to canonical
# ones. Only differing names are listed, so most articles need no map at all.

def article_stem(article):
    """The post stem a map is filed under, from a path or a stem."""
    if not article:
        return None
    base = os.path.basename(article)
    return base[:-len(".markdown")] if base.endswith(".markdown") else base


def load_article_map(article, directory=None):
    directory = directory or ARTICLES
    stem = article_stem(article)
    if not stem:
        return {}
    path = os.path.join(directory, stem + ".json")
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as fh:
        amap = json.load(fh)
    for k, v in amap.items():
        if not (ANCHOR_RE.match(k) and ANCHOR_RE.match(v)):
            raise SourceError(f"{path}: {k!r} -> {v!r} is not a pair of anchors")
    return amap


def save_article_map(article, amap, directory=None):
    directory = directory or ARTICLES
    stem = article_stem(article)
    path = os.path.join(directory, stem + ".json")
    amap = {k: v for k, v in sorted(amap.items()) if k != v}
    if not amap:
        if os.path.exists(path):
            os.remove(path)
        return
    os.makedirs(directory, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(amap, fh, indent=1, sort_keys=True)
        fh.write("\n")


def load_listed(article, directory=None):
    """Anchors the article's reference list names that its prose does not cite.

    WHY. Some articles, A207 among them, close with a bibliography of the works
    the account rests on and cite none of them in the prose. The generated list
    would otherwise keep only what the prose cites and drop every one of those
    works. Filed per article in `_sources/articles/<post stem>.listed.json`, a
    list of anchors, written by the import from the legacy reference list.
    """
    directory = directory or ARTICLES
    stem = article_stem(article)
    path = os.path.join(directory, f"{stem}.listed.json") if stem else None
    if not path or not os.path.exists(path):
        return set()
    with open(path, encoding="utf-8") as fh:
        listed = json.load(fh)
    if not (isinstance(listed, list) and all(isinstance(a, str) and ANCHOR_RE.match(a) for a in listed)):
        raise SourceError(f"{path}: a list of anchors")
    return set(listed)


def save_listed(article, anchors, directory=None):
    directory = directory or ARTICLES
    path = os.path.join(directory, f"{article_stem(article)}.listed.json")
    if not anchors:
        if os.path.exists(path):
            os.remove(path)
        return
    os.makedirs(directory, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(sorted(anchors), fh, indent=1)
        fh.write("\n")


def load_prose_links(article, directory=None):
    """Anchors whose links in the article name a document in the prose, not cite it.

    `[Economic Cooperation Act of 1948]` ends with a year but is the statute's
    name in a sentence, so relabelling it would rewrite prose. Filed per article in
    `_sources/articles/<post stem>.links.json` as a list of anchors, each a decision.
    """
    directory = directory or ARTICLES
    stem = article_stem(article)
    path = os.path.join(directory, f"{stem}.links.json") if stem else None
    if not path or not os.path.exists(path):
        return set()
    with open(path, encoding="utf-8") as fh:
        links = json.load(fh)
    if not (isinstance(links, list) and all(isinstance(a, str) and ANCHOR_RE.match(a) for a in links)):
        raise SourceError(f"{path}: a list of anchors")
    return set(links)


def article_index(records, article=None):
    """`resolve_index`, overlaid with the article's own name map.

    The overlay wins, so an article whose `research_smith_2020` is a different
    work from the store's `research_smith_2020` resolves to its own.
    """
    index = resolve_index(records)
    for name, canon in load_article_map(article).items():
        if canon not in records:
            raise SourceError(f"{article_stem(article)}: {name} maps to {canon}, which is not stored")
        index[name] = (canon, None)
    return index


def resolve_index(records):
    """Map every usable anchor to (canonical anchor, fragment or None)."""
    index = {}
    for a, r in records.items():
        names = [(a, None)] + [(x, None) for x in r.get("aliases", [])] \
            + list(r.get("locators", {}).items())
        for name, frag in names:
            if name in index:
                raise SourceError(f"anchor {name!r} resolves to both {index[name][0]!r} and {a!r}")
            index[name] = (a, frag)
    return index


def save_records(records, directory=RECORDS):
    """Write every record to its shard, sorted, replacing the shard files."""
    shards = {}
    for a in sorted(records):
        shards.setdefault(shard_of(a), []).append(records[a])
    os.makedirs(directory, exist_ok=True)
    for old in glob.glob(os.path.join(directory, "*.jsonl")):
        if os.path.basename(old)[:-6] not in shards:
            os.remove(old)
    for s, rows in shards.items():
        with open(os.path.join(directory, f"{s}.jsonl"), "w", encoding="utf-8") as f:
            for r in rows:
                f.write(_dump(r) + "\n")


def save_venues(venues, path=VENUES):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        for k in sorted(venues):
            f.write(_dump(venues[k]) + "\n")


# --------------------------------------------------------------- validation

def _require(cond, msg):
    if not cond:
        raise SourceError(msg)


FIELDS = {
    "anchor", "aliases", "locators", "kind", "section", "rule", "synthesis", "stake", "encyclopaedia",
    "authors", "editors", "year", "title", "title_published", "container", "venue", "volume", "issue",
    "pages", "publisher", "number", "doi", "url", "revision", "accessed", "post", "evidence", "note",
    "short_title", "published", "periodical", "primary", "publisher_registry", "original_year",
    "doi_primary",
}


def validate_record(r, venues):
    a = r.get("anchor", "?")
    unknown = sorted(set(r) - FIELDS)
    _require(not unknown, f"{a}: unknown field(s) {', '.join(unknown)}")
    for date_field, pattern in (("published", r"^\d{4}(-\d{2}(-\d{2})?)?$"), ("accessed", r"^\d{4}-\d{2}-\d{2}$")):
        _require(date_field not in r or re.match(pattern, str(r[date_field])),
                 f"{a}: {date_field} must be ISO, got {r.get(date_field)!r}")
    for flag in ("synthesis", "stake", "encyclopaedia", "periodical", "primary"):
        _require(flag not in r or isinstance(r[flag], bool), f"{a}: {flag} must be true or false")
    _require(isinstance(a, str) and ANCHOR_RE.match(a), f"{a}: anchor must match {ANCHOR_RE.pattern}")
    kind = r.get("kind")
    _require(kind in KINDS, f"{a}: unknown kind {kind!r}")
    rule, section = r.get("rule"), r.get("section")
    _require(rule in RULE_SECTIONS, f"{a}: rule must be 1 to 7, got {rule!r}")
    _require(section in RULE_SECTIONS[rule], f"{a}: rule {rule} cannot place a source in {section!r}")
    expected = classify(r, venues)
    _require(expected == (rule, section),
             f"{a}: recorded as rule {rule}, {section!r}, but the rules give {expected}")
    for name in ("aliases",):
        v = r.get(name, [])
        _require(isinstance(v, list) and all(isinstance(x, str) and ANCHOR_RE.match(x) for x in v),
                 f"{a}: {name} must be a list of anchors")
    loc = r.get("locators", {})
    _require(isinstance(loc, dict) and all(ANCHOR_RE.match(k) and FRAGMENT_RE.match(f)
                                           for k, f in loc.items()),
             f"{a}: locators must map anchors to fragment ids")
    if kind == "related-post":
        _require(re.match(r"^\d{4}-\d{2}-\d{2}-[a-z0-9_-]+$", r.get("post", "")),
                 f"{a}: related-post needs `post` as a dated post filename stem")
        return
    _require(isinstance(r.get("title"), str) and r["title"].strip(), f"{a}: title required")
    year = r.get("year")
    # A YEAR FROM 1000: A266 cites the papal bull Inter caetera of 1493.
    _require(year is None or (isinstance(year, int) and 1000 <= year <= 2100), f"{a}: bad year {year!r}")
    authors = r.get("authors", [])
    _require(isinstance(authors, list) and isinstance(r.get("editors", []), list),
             f"{a}: authors and editors must be lists")
    for p in authors + r.get("editors", []):
        ok = (isinstance(p, dict) and (
            (set(p) <= {"family", "given"} and p.get("family")) or
            (set(p) <= {"name", "short"} and p.get("name"))))
        _require(ok, f"{a}: author {p!r} must be {{family, given}} or {{name, short}}")
    _require(bool(r.get("doi")) != bool(r.get("url")), f"{a}: exactly one of doi and url")
    if r.get("url"):
        # AN IRC CHANNEL, `irc://irc.freenode.net/elixir-lang` in A4 to A8, is a place a
        # tutorial sent its reader, so its scheme is accepted with the web's.
        _require(r["url"].startswith(("https://", "http://", "irc://")), f"{a}: url scheme")
    if kind == "wikipedia":
        rev = r.get("revision") or {}
        _require(isinstance(rev.get("oldid"), int) and re.match(r"^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ$",
                                                                 rev.get("timestamp", "")),
                 f"{a}: wikipedia needs revision.oldid and revision.timestamp")
        _require(f"oldid={rev['oldid']}" in r["url"], f"{a}: wikipedia url must pin oldid {rev['oldid']}")
        _require(str(year) == rev["timestamp"][:4], f"{a}: wikipedia year must be the revision year")
    if kind in ("journal-article", "proceedings-paper", "abstract", "chapter"):
        _require(r.get("container"), f"{a}: {kind} needs container")
    # Registries emit placeholders such as `n/a-n/a` for pages. Kopp and Lean
    # 2011 arrived from Crossref that way.
    _require("n/a" not in str(r.get("pages", "")).lower(), f"{a}: pages hold a placeholder, {r.get('pages')!r}")
    if kind in ("journal-article", "proceedings-paper"):
        _require(r.get("venue") in venues, f"{a}: venue {r.get('venue')!r} not in venues.jsonl")


VENUE_FIELDS = {"venue", "peer_reviewed", "checked", "basis", "evidence", "since", "reviewers", "magazine",
                "publisher", "class", "via", "no_publisher_credit"}
EVIDENCE_FIELDS = {"url", "quote", "read", "method"}


def validate_venue(v):
    """A venue is credited with peer review only when it can be said BY WHOM.

    THE END THIS SERVES. "Peer-Reviewed" tells a reader that people
    independent of the authors assessed the work before publication. A venue
    is credited only when the database can answer the question a reader would
    ask, reviewed by whom, so `peer_reviewed` true requires `reviewers`, that
    answer in a few words, such as "two or more independent reviewers selected
    by the editors". A statement that a journal is "peer-reviewed" without
    saying by whom does not answer it.

    THE ANSWER MUST BE READ, NOT RECALLED OR SUMMARISED. `evidence` is a list
    of sources, each with the `url`, a verbatim `quote`, the date it was
    `read` and the `method`. Only `fetched`, a page actually read, can support
    the answer. A search-engine `snippet` may paraphrase and is kept only as a
    lead. Any source the venue speaks through counts: its own pages, its
    publisher's, its editors' published editorials, or its society's
    magazine. `since` is the first year the evidence covers when it gives one,
    and a work published earlier is not credited.
    """
    name = v.get("venue")
    _require(isinstance(name, str) and name, "venue name required")
    unknown = sorted(set(v) - VENUE_FIELDS)
    _require(not unknown, f"{name}: unknown venue field(s) {', '.join(unknown)}")
    _require(isinstance(v.get("peer_reviewed"), bool), f"{name}: peer_reviewed must be true or false")
    _require(isinstance(v.get("basis"), str) and v["basis"], f"{name}: basis required")
    _require(isinstance(v.get("checked"), bool), f"{name}: checked must be true or false")
    evidence = v.get("evidence", [])
    _require(isinstance(evidence, list), f"{name}: evidence must be a list of sources")
    for ev in evidence:
        _require(isinstance(ev, dict) and set(ev) == EVIDENCE_FIELDS
                 and all(isinstance(ev[k], str) and ev[k] for k in EVIDENCE_FIELDS),
                 f"{name}: evidence needs exactly url, quote, read and method")
        _require(ev["method"] in ("fetched", "snippet"), f"{name}: evidence method must be fetched or snippet")
        _require(re.match(r"^\d{4}-\d{2}-\d{2}$", ev["read"]), f"{name}: evidence read must be YYYY-MM-DD")
    if "since" in v:
        _require(isinstance(v["since"], int) and not isinstance(v["since"], bool), f"{name}: since must be a year")
    if "magazine" in v:
        _require(v["magazine"] is True and not v["peer_reviewed"],
                 f"{name}: magazine is true or absent, and a magazine is not credited with peer review")
    if "reviewers" in v:
        _require(isinstance(v["reviewers"], str) and v["reviewers"].strip(), f"{name}: reviewers must be text")
    if v["peer_reviewed"]:
        _require(v["checked"], f"{name}: peer_reviewed requires checked, the venue's own statement read")
        _require(v.get("reviewers"), f"{name}: peer_reviewed requires reviewers, the answer to by whom")
        _require(any(ev["method"] == "fetched" for ev in evidence),
                 f"{name}: peer_reviewed requires evidence fetched from a source the venue speaks through")


def credits_review(r, venues):
    """True only when the record's venue is verified as refereeing and covers its year."""
    venue = venues.get(r.get("venue"), {})
    if (venue.get("peer_reviewed") is not True or venue.get("checked") is not True
            or not venue.get("reviewers")):
        return False
    since = venue.get("since")
    return since is None or (isinstance(r.get("year"), int) and r["year"] >= since)


def validate(records=None, venues=None):
    venues = load_venues() if venues is None else venues
    records = load_records() if records is None else records
    for v in venues.values():
        validate_venue(v)
    for r in records.values():
        validate_record(r, venues)
    resolve_index(records)
    return len(records), len(venues)


# ------------------------------------------------------------ classification

def classify(r, venues):
    """(rule, section) by the first rule of CITATION_STYLE.md that applies.

    `synthesis` marks a work that synthesises others rather than reporting its
    own, such as a review article. `stake` marks a publisher with a financial or
    institutional interest in the subject. Both are human decisions recorded on
    the record, because no registry metadata answers them.
    """
    kind = r.get("kind")
    if kind == "related-post":
        return 1, "Related Posts"
    if kind == "wikipedia" or r.get("encyclopaedia"):
        return 2, "Tertiary Sources"
    if kind in ("journal-article", "proceedings-paper"):
        # A MAGAZINE'S FEATURES ARE GENERAL SOURCES under rule 7, edited and
        # commissioned rather than refereed, whoever publishes the magazine.
        if venues.get(r.get("venue"), {}).get("magazine"):
            return 7, "General Sources"
        reviewed = credits_review(r, venues)
        # A REVIEW IS SECONDARY WHETHER OR NOT ITS VENUE IS VERIFIED. Secondary
        # Sources is about synthesis, not refereeing, so a review in a venue
        # whose policy could not be read takes rule 5, like a scholarly book.
        if r.get("synthesis"):
            return (3, "Secondary Sources") if reviewed else (5, "Secondary Sources")
        if reviewed:
            return 3, "Primary Sources, Peer-Reviewed"
        # DEFAULT DENY. A venue whose full-paper review is not verified from its
        # own statement, or whose evidence does not reach back to the work's
        # year, is not credited with peer review.
        return 4, "Primary Sources, Non-Peer-Reviewed"
    # Rule 4 names theses, datasets, standards and the documentation of open-source
    # projects. `other` is a registry work of no stated type, placed by default deny.
    if kind in ("abstract", "preprint", "report", "thesis", "dataset", "standard", "documentation", "other"):
        return 4, "Primary Sources, Non-Peer-Reviewed"
    if kind == "chapter":
        return (5, "Secondary Sources") if r.get("synthesis") else (4, "Primary Sources, Non-Peer-Reviewed")
    if kind == "book":
        return 5, "Secondary Sources"
    if kind == "web-page":
        # A FIRST-HAND RECORD on a web page, such as testimony, a speech or an
        # official statistical release, is primary under rule 4 before the
        # publisher's stake is asked about.
        if r.get("primary"):
            return 4, "Primary Sources, Non-Peer-Reviewed"
        return (6, "Commercial Sources") if r.get("stake") else (7, "General Sources")
    raise SourceError(f"{r.get('anchor')}: no rule applies to kind {kind!r}")


# ---------------------------------------------------------------- formatting

_MD_SPECIAL = re.compile(r"([\\`*_\[\]<>{}$|#])")


def md_escape(s):
    """Text safe to place in a Markdown list item.

    Backslash-escapes the characters that open emphasis, code, links, inline
    HTML, Liquid tags, MathJax or tables, so registry text cannot change how the
    surrounding page parses. kramdown accepts every one of these escapes.
    """
    s = re.sub(r"\s+", " ", s).strip()
    return _MD_SPECIAL.sub(r"\\\1", s)


def clean_text(s):
    """Normalise registry text before it is stored: entities, tags, odd hyphens."""
    import html
    s = s or ""
    # DOUBLY ESCAPED MARKUP ARRIVES FROM REGISTRIES. An AIAA proceedings title came
    # as `&amp;lt;BR&amp;gt;`, which one unescape leaves as visible `&lt;BR&gt;`.
    # Unescaping is repeated until stable, bounded because each pass shortens it.
    for _ in range(3):
        t = html.unescape(s)
        if t == s:
            break
        s = t
    # A line-break tag separates two names, so it becomes a space, not nothing.
    s = re.sub(r"<br\s*/?>", " ", s, flags=re.I)
    s = re.sub(r"<[^>]+>", "", s)
    s = s.replace("\u2010", "-").replace("\u2011", "-").replace("\u00a0", " ")
    s = re.sub(r"\s+:", ":", s)  # a space before a colon is a registry habit, never Chicago
    return re.sub(r"\s+", " ", s).strip()


def page_range(pages):
    """Chicago's abbreviated page range, as in 471–85, 101–8, 1051–54.

    All digits are kept below 100, at an exact hundred, and whenever anything
    above the last two digits changes, as in 498–532 and 1496–1504. Within one
    hundred, 1 to 9 keep only the changed digit and the rest keep two.
    Non-numeric pages, such as electronic article numbers, pass through.
    """
    if not pages:
        return ""
    pages = pages.replace("--", "-").replace("\u2013", "-")
    m = re.match(r"^\s*(\d+)\s*-\s*(\d+)\s*$", pages)
    if not m:
        return pages.strip()
    a, b = m.group(1), m.group(2)
    ia = int(a)
    if ia < 100 or ia % 100 == 0 or len(a) != len(b) or a[:-2] != b[:-2] or int(b) <= ia:
        return f"{a}\u2013{b}"
    if ia % 100 < 10:
        tail = b[-2:]
        return f"{a}\u2013{tail.lstrip('0') if a[-2] == b[-2] else tail}"
    return f"{a}\u2013{b[-2:]}"


def _ends_terminal(s):
    return s.rstrip().endswith((".", "?", "!"))


def _sentence(s):
    s = s.strip()
    return s if _ends_terminal(s) else s + "."


def _quoted(title):
    """A title in quotation marks with its terminal period inside, Chicago style."""
    t = md_escape(title.replace('"', "'"))
    return f'"{t}"' if _ends_terminal(title) else f'"{t}."'


def _person(p, invert):
    if "name" in p:
        return f"{p['short']} ({p['name']})" if p.get("short") else p["name"]
    fam, giv = p["family"], p.get("given", "")
    if not giv:
        return fam
    # A GENERATIONAL SUFFIX FOLLOWS THE GIVEN NAMES WHEN INVERTED, `Sauer, C., Jr.`,
    # and follows the family name without a comma otherwise, `C. Sauer Jr.`
    m = re.match(r"^(.*?)\s+(Jr\.|Sr\.|II|III|IV)$", fam)
    if invert and m:
        return f"{m.group(1)}, {giv}, {m.group(2)}"
    return f"{fam}, {giv}" if invert else f"{giv} {fam}"


def creators(r):
    """The people a reference is listed under: its authors, or for an edited book its editors.

    Chicago puts an editor in the author position when a book has no
    author, so the editor leads the entry, the in-text label and the sort.
    """
    return r.get("authors") or (r.get("editors", []) if r.get("kind") == "book" else [])


def author_list(authors):
    """Reference-list authors. Up to six all named, more than six give three and et al."""
    if not authors:
        return ""
    shown = authors if len(authors) <= 6 else authors[:3]
    names = [_person(p, i == 0) for i, p in enumerate(shown)]
    if len(authors) > 6:
        return ", ".join(names) + ", et al."
    if len(names) == 1:
        return names[0]
    # THE COMMA BEFORE `and` closes an inverted name, `Ward, Geoffrey C., and Ken Burns`.
    # A first author known by surname alone is not inverted, so two such read
    # `Astrahan and Jacobs`, not `Astrahan, and Jacobs`.
    if len(names) == 2 and not shown[0].get("given"):
        return f"{names[0]} and {names[1]}"
    return ", ".join(names[:-1]) + ", and " + names[-1]


def _short_name(p):
    """The name an in-text citation uses. A generational suffix is not part of it."""
    return p.get("short") or p.get("name") or re.sub(r"\s+(?:Jr\.|Sr\.|II|III|IV)$", "", p["family"])


_MINOR_END = {"a", "an", "the", "and", "or", "of", "for", "in", "on", "to", "at", "by", "with", "under", "from"}


def short_title(title):
    """Up to four words of a title for an in-text label, Chicago's limit.

    Punctuation becomes a space, a leading section number is dropped, and minor
    words at the end are dropped, so `Officers under Attack—the Thin Blue Line`
    gives `Officers under Attack`.
    """
    # A SUBTITLE IS NOT PART OF A SHORT TITLE, Chicago 15.32, so the title is cut
    # at a colon or a dash first. `Multiple Chemical Sensitivity — nur ein
    # Schlagwort?` otherwise gave `Multiple Chemical Sensitivity Nur`.
    t = re.split(r":\s|\s[\u2014\u2013-]\s|\u2014", title)[0] or title
    t = t.replace("\u2019", "'").replace("\u2018", "'")   # the labels write straight quotes
    t = re.sub(r"^\s*\d+[.)]\s*", "", t)
    t = re.sub(r"[()\[\]]", " ", t)
    t = re.sub(r"[:;,\u2014\u2013\-]+(?=\s|$)|(?<=\s)[\u2014\u2013\-]+|[\u2014\u2013]", " ", t)
    words = t.split()[:4]
    while len(words) > 1 and words[-1].lower() in _MINOR_END:
        words.pop()
    return " ".join(words)


def cite_label(r):
    """In-text author label without the year. Two named at most, else et al."""
    au = creators(r)
    if not au:
        # A WORK WITH NO AUTHOR is cited in the text by a shortened title. A recorded
        # `short_title` is a decision; without one, the first four words are used,
        # Chicago's limit and the form the articles' own labels took.
        return r.get("short_title") or short_title(r["title"])
    if len(au) == 1:
        return _short_name(au[0])
    if len(au) == 2:
        return f"{_short_name(au[0])} and {_short_name(au[1])}"
    return f"{_short_name(au[0])} et al."


def _year_text(r, suffix=""):
    """The year with its 13.114 suffix, or `n.d.` with a hyphenated one."""
    if r.get("original_year") and r.get("year"):
        return f"({r['original_year']}) {r['year']}{suffix}"
    if r.get("year"):
        return f"{r['year']}{suffix}"
    return "n.d." + (f"-{suffix}" if suffix else "")


def _label_year(r, suffix=""):
    """The year an in-text label carries: a reprint's original year, else the entry's."""
    if r.get("original_year"):
        return f"{r['original_year']}{suffix}"
    return _year_text(r, suffix)


def _target(r):
    """The link-definition target for a record's canonical anchor."""
    if r["kind"] == "related-post":
        return "{% post_url " + r["post"] + " %}"
    return f"https://doi.org/{r['doi']}" if r.get("doi") else r["url"]


def _link(r):
    """The visible identifier, linked through the record's anchor."""
    return f"[{md_escape(_target(r))}][{r['anchor']}]"


def _long_date(iso):
    """`2026-10-21` as `October 21, 2026`, the form Chicago gives an access date."""
    d = datetime.date.fromisoformat(iso[:10])
    return f"{MONTHS[d.month - 1]} {d.day}, {d.year}"


def _month_day(iso):
    d = datetime.date.fromisoformat(iso[:10])
    return f"{MONTHS[d.month - 1]} {d.day}"


