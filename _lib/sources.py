def entry(r, suffix="", posts_dir=POSTS):
    """One reference-list entry as a Markdown list item body.

    A REPRINT leads with its original year in parentheses before the year of
    the version linked, `Reynolds, John C. (1972) 1998.`, and is cited in the text
    by the original year, so that the prose dates the work when it was written.
    """
    return _entry(r, suffix, posts_dir)


def _entry(r, suffix="", posts_dir=POSTS):
    kind = r["kind"]
    if kind == "related-post":
        f = related_post_fields(r, posts_dir)
        who = _person(f["author"], True)
        return (f"{md_escape(who)}. {f['date'][:4]}. {_quoted(f['title'])} *{md_escape(f['blog'])}*, "
                f"{_month_day(f['date'])}. [{md_escape(f['url'])}][{r['anchor']}]")
    link = _link(r)
    year = _year_text(r, suffix)
    if kind == "wikipedia":
        ts = r["revision"]["timestamp"]
        return (f"{_quoted(r['title'])} {year}. Wikipedia. Last modified {_month_day(ts)}, "
                f"at {ts[11:16]} (UTC). {link}")
    au = author_list(creators(r))
    if au and not r.get("authors"):
        au += ", ed." if len(creators(r)) == 1 else ", eds."
    # `n.d.` ENDS IN ITS OWN FULL STOP, which closes the element, so none is added.
    ydot = year if year.endswith(".") else year + "."
    lead = f"{md_escape(_sentence(au))} {ydot}" if au else f"{_quoted(r['title'])} {ydot}"
    title_q = "" if not au else " " + _quoted(r["title"])
    title_i = f" *{md_escape(r['title'])}*." if au else ""
    container = md_escape(r.get("container", ""))
    publisher = f" {md_escape(_sentence(r['publisher']))}" if r.get("publisher") else ""
    number = f" {md_escape(_sentence(r['number']))}" if r.get("number") else ""
    if kind == "journal-article":
        tail = f" *{container}*"
        vol, iss, pg = r.get("volume"), r.get("issue"), page_range(r.get("pages", ""))
        if vol:
            tail += f" {md_escape(vol)}"
        if iss:
            iss = re.sub(r"^(\d+)-(\d+)$", "\\1\u2013\\2", iss)
            tail += f" ({md_escape(iss)})" if vol else f", no. {md_escape(iss)}"
        if pg:
            tail += f": {md_escape(pg)}"
        return f"{lead}{title_q}{tail}. {link}"
    if kind in ("proceedings-paper", "chapter"):
        eds = r.get("editors", [])
        ed = ", edited by " + md_escape(", ".join(_person(p, False) for p in eds)) if eds else ""
        vol = f", vol. {md_escape(r['volume'])}" if r.get("volume") else ""
        return f"{lead}{title_q} In *{container}*{vol}{ed}.{number}{publisher} {link}"
    if kind == "abstract":
        return f"{lead}{title_q} Abstract {md_escape(r['number'])}, *{container}*.{publisher} {link}"
    if kind == "preprint":
        return f"{lead}{title_q} Preprint, {container}. {link}"
    if kind in ("book", "report", "dataset", "standard", "other"):
        # With no author the title leads, set in italics as the work's own title.
        if not au:
            return f"*{md_escape(r['title'])}*. {_sentence(year)}{number}{publisher} {link}"
        return f"{lead}{title_i}{number}{publisher} {link}"
    if kind == "thesis":
        inst = f", {md_escape(r['container'])}" if r.get("container") else ""
        return f"{lead}{title_q} {md_escape(r.get('number') or 'PhD diss.')}{inst}. {link}"
    if kind == "documentation":
        site = f" {md_escape(_sentence(r['container']))}" if r.get("container") else ""
        when = f" Accessed {_long_date(r['accessed'])}." if r.get("accessed") else ""
        return f"{lead}{title_q}{site}{when} {link}"
    if kind == "web-page":
        # A PERIODICAL'S NAME IS ITALIC and a website's is not. A published date
        # follows the name, `*Foreign Affairs*, March 4.`; with none, the access
        # date ends the entry. A month or a day is printed only when recorded.
        name = r.get("container") or ""
        site = (f" *{md_escape(name)}*" if r.get("periodical") else f" {md_escape(name)}") if name else ""
        pub = r.get("published") or ""
        if len(pub) >= 7:
            site += ", " + (_month_day(pub) if len(pub) == 10 else MONTHS[int(pub[5:7]) - 1])
        site = (site + ".") if site else ""
        if r.get("revision", {}).get("modified"):
            when = f" Last modified {r['revision']['modified']}."
        elif not pub and r.get("accessed"):
            when = f" Accessed {_long_date(r['accessed'])}."
        elif pub:
            when = ""
        else:
            raise SourceError(f"{r['anchor']}: web page needs a published, modified or accessed date")
        return f"{lead}{title_q}{site}{when} {link}"
    raise SourceError(f"{r['anchor']}: kind {kind} has no template")


def _fold(s):
    s = unicodedata.normalize("NFKD", s)
    return "".join(c for c in s if not unicodedata.combining(c)).casefold()


def _title_key(t):
    return _fold(re.sub(r"^(a|an|the)\s+", "", t.strip(), flags=re.I))


def sort_key(r, posts_dir=POSTS):
    """Chicago 13.112. First element, then year, then title without its article."""
    if r["kind"] == "related-post":
        f = related_post_fields(r, posts_dir)
        return ("sechter", f["date"], _title_key(f["title"]))
    au = creators(r)
    if au:
        # Family names only. Registries give one person's given name in full in
        # one record and as initials in the next, which must not split them.
        first = tuple(_fold(p.get("family") or p.get("short") or p.get("name")) for p in au)
        return (first, r.get("year") or 0, _title_key(r["title"]))
    return ((_title_key(r["title"]),), r.get("year") or 0, "")


def year_suffixes(recs):
    """Chicago 13.114. Same in-text label and year in one article take a, b, c.

    A work cited by its short title takes a suffix too when two short titles and
    years coincide, as the two DOIs of the chapter `Death by Perfume` in A377 did,
    since otherwise one label would name two entries.
    """
    groups = {}
    for r in recs:
        if r["kind"] in ("related-post", "wikipedia"):
            continue
        groups.setdefault((cite_label(r), r.get("original_year") or r.get("year")), []).append(r)
    out = {}
    for key, rs in groups.items():
        if len(rs) > 1:
            for i, r in enumerate(sorted(rs, key=lambda x: _title_key(x["title"]))):
                out[r["anchor"]] = "abcdefghijklmnopqrstuvwxyz"[i]
    return out


# ------------------------------------------------------------------ articles

# A link pair with its text, which `post.LINK_PAIR` does not capture.
USE_RE = re.compile(rf"\[((?:[^\[\]]|\\\[|\\\])+)\]\[({post.ANCHOR})\]")


def split_article(text):
    """(everything before the References heading, the section after it).

    Delegates to `post.split`, and additionally insists the heading appears
    exactly once as a line of its own, because everything after it is replaced.
    """
    n = len(re.findall(rf"(?m)^{re.escape(post.REFERENCES_HEADING)}$", text))
    if n != 1:
        raise SourceError(f"expected exactly one `{post.REFERENCES_HEADING}` heading line, found {n}")
    front, body, refs = post.split(text)
    head = post.REFERENCES_HEADING + "\n"
    if not refs.startswith(head):
        raise SourceError("the References heading must be followed by a newline")
    return front + body, refs[len(head):]


def cited_anchors(body):
    return {a for _t, a in USE_RE.findall(body)}


def generate(text, records=None, venues=None, posts_dir=POSTS, article=None):
    """The References section, heading included, for an article's current body."""
    records = load_records() if records is None else records
    venues = load_venues() if venues is None else venues
    index = article_index(records, article)
    body, _old = split_article(text)
    cited = cited_anchors(body)
    used = cited | load_listed(article)
    missing = sorted(a for a in used if a not in index)
    if missing:
        raise SourceError(f"anchors cited but not in the database: {', '.join(missing)}")
    canon = sorted({index[a][0] for a in used})
    recs = [records[a] for a in canon]
    for r in recs:
        validate_record(r, venues)
    suffix = year_suffixes(recs)
    # EACH ENTRY LINKS THROUGH A NAME THE ARTICLE USES, its canonical anchor when
    # the article uses that, so a mapped article's References carry its own names.
    via = {}
    for c in canon:
        names = sorted(a for a in used if index[a] == (c, None))
        via[c] = c if c in names or not names else names[0]
    out = ["## References", "", MARKER, ""]
    for sec in SECTIONS:
        rows = sorted((r for r in recs if r["section"] == sec), key=lambda r: sort_key(r, posts_dir))
        if not rows:
            continue
        out += [f"### {sec}", ""]
        out += [f"- {entry(dict(r, anchor=via[r['anchor']]), suffix.get(r['anchor'], ''), posts_dir)}"
                for r in rows]
        out.append("")
    defs = {via[r["anchor"]]: _target(r) for r in recs}
    # ONLY NAMES SOMETHING USES ARE DEFINED: a listed work the prose also cites under
    # another name links through that name, and a definition for the listed name would
    # be one nothing uses, which `_verify.py` refuses.
    for a in cited:
        ca, frag = index[a]
        defs[a] = _target(records[ca]) + (f"#{frag}" if frag else "")
    out += [f"[{a}]: {defs[a]}" for a in sorted(defs)]
    return "\n".join(out) + "\n"


# A SURVEY ENTRY IS NOT AN IN-TEXT CITATION. The harvested surveys list works in
# the body, one per line, as `- [Pike and others, 2001, Title][anchor]`, a form
# no in-text label takes, since a label never carries a title after its year.
# A LIST ITEM THAT IS ONLY A LINK is a list entry, however its text is written:
# A369 lists works by title alone, A370 to A373 as `Author and others, Year, Title`.
_SURVEY_ENTRY = re.compile(r"(?m)^\s*- \[([^\]\n]+)\]\[([a-z0-9_]+)\]\s*$")
# A CITATION LABEL ENDS WITH ITS YEAR, `Kopp and Lean 2011` or `Smith n.d.`, with
# an optional locator after a comma. A link on a term, `[inkwell][ref_inkwell]` or
# `[the eBPF verifier][...]`, is a hyperlink in the prose and is not relabelled.
_CITATION_LABEL = re.compile(r"^(?P<names>.+?)\s+(?:\d{4}[a-z]?|n\.d\.(?:-[a-z])?)(?:, .*)?$")
# THE NAME PART OF A LABEL holds names and nothing else: capitalised words, `and`,
# `et al.`, commas and surname particles. A link woven into a sentence, `[Clausius in
# 1850]` or `[section 5 of the Firearms Act 1968]`, holds other words and is prose.
_NAME_TOKEN = re.compile(r"^(?:and|et|al\.?|&|de|van|von|der|den|da|du|la|le|di|del|dos|das|ter|ten|y|[A-Z\u00C0-\u00DE\u0100-\u024F][\w'\u2019\-.]*)$")


def is_citation_label(text):
    """True when link text has the form of an in-text citation label, names then a year."""
    m = _CITATION_LABEL.match(text)
    if not m:
        return False
    tokens = [t for t in re.split(r"[\s,]+", m.group("names").strip()) if t]
    # An organisation's name may hold `of`, `the` and `for`, but must open with a capital.
    if not tokens or not (_NAME_TOKEN.match(tokens[0]) and tokens[0][:1].isupper() or tokens[0] in ("de", "van", "von", "da", "di", "du", "le", "la")):
        return False
    # `and colleagues`, `and others` and `and coauthors` are the articles' own ways
    # of writing et al., so such a label is a citation and is normalised.
    return all(_NAME_TOKEN.match(t) or t in ("of", "the", "for", "colleagues", "others", "coauthors")
               for t in tokens)


def _title_label(text, r):
    """Whether link text is `<the opening words of the work's title> <year>`."""
    m = _CITATION_LABEL.match(text)
    if not m or not r.get("title"):
        return False
    key = lambda x: re.sub(r"[^a-z0-9]", "", x.lower())
    head = key(m.group("names"))
    return len(head) >= 6 and key(r["title"]).startswith(head)


def survey_entries(body):
    """{(text, anchor)} of the body's survey-list entries, which the label check skips."""
    return set(_SURVEY_ENTRY.findall(body))


def label_errors(text, records=None, posts_dir=POSTS, article=None):
    """In-text links whose author and year disagree with the database.

    Only author-based sources are checked. Wikipedia articles and related posts
    are cited by title in running prose and carry free link text.
    """
    records = load_records() if records is None else records
    index = article_index(records, article)
    body, _ = split_article(text)
    recs = [records[a] for a in sorted({index[a][0] for a in cited_anchors(body) if a in index})]
    suffix = year_suffixes(recs)
    skip = survey_entries(body)
    prose = load_prose_links(article)
    errs = []
    for t, a in USE_RE.findall(body):
        if a not in index or (t, a) in skip or a in prose:
            continue
        r = records[index[a][0]]
        # A SHORT-TITLE LABEL IN LOWER CASE, `Earth oblateness in terms 1959`, is a
        # citation too when its words begin the work's own title, as the X-Planes
        # surveys wrote labels for works their harvest held without authors.
        if not is_citation_label(t) and not _title_label(t, r):
            continue
        # A work with no author is still cited by label and year, the label being
        # its short title, so only encyclopaedia articles and posts are exempt.
        if r["kind"] in ("related-post", "wikipedia"):
            continue
        # A LABEL NEVER HOLDS A SQUARE BRACKET, which would break the link around it.
        want = re.sub(r"[\[\]]", "", f"{cite_label(r)} {_label_year(r, suffix.get(r['anchor'], ''))}")
        flat = re.sub(r"\s+", " ", t)              # a wrapped label is the same label
        if flat != want and not flat.startswith(want + ", "):
            errs.append((t, a, want))
    return errs


# DOTALL, since a label can wrap across a line, `[Castles and De Leeuw\n1953]`.
_LABEL_HEAD = re.compile(r"^.*?\b\d{4}[a-z]?(?=$|, )", re.S)


def fix_labels(text, records=None, article=None):
    """(new text, [(old, new)]) with every in-text label set to what the database gives.

    Only the label head, the names and the year, is replaced. A locator after
    it, as in `Smith 2020, p. 5`, is kept. A label whose head cannot be found is
    left alone and returned with `None` as its replacement, for a person to fix,
    because guessing where a free-text label ends could rewrite prose.
    """
    body, refs = split_article(text)
    changes = []
    for t, a, want in label_errors(text, records, article=article):
        m = _LABEL_HEAD.match(t)
        if not m:
            changes.append((t, None))
            continue
        new = want + t[m.end():]
        # A LABEL WRAPPED ACROSS A LINE keeps its line break before the year, so the
        # paragraph keeps its lines and the comparison of lines stays aligned.
        if "\n" in t[:m.end()]:
            new = re.sub(r" (?=\d{4}[a-z]?(?:$|, ))", "\n", want, count=1) + t[m.end():]
        old_link, new_link = f"[{t}][{a}]", f"[{new}][{a}]"
        if old_link in body:
            body = body.replace(old_link, new_link)
            changes.append((t, new))
    # `split_article` returns the section without its heading, so it is restored.
    out = body + post.REFERENCES_HEADING + "\n" + refs
    split_article(out)
    return out, changes


_ETAL = re.compile(r"\s*(,?\s*et al\.?|\s+and (?:others|colleagues|coauthors))$")


def _same_people(old, new, fold):
    """Whether two label name parts name the same people, `et al.` standing for three or more."""
    def names(x):
        x = _ETAL.sub("", x.strip())
        return [fold(p.strip()) for p in re.split(r",\s*|\s+and\s+|\s*&\s*", x) if p.strip()]
    o_etal, n_etal = bool(_ETAL.search(old.strip())), bool(_ETAL.search(new.strip()))
    o, n = names(old), names(new)
    if n_etal:
        # `et al.` is right for three or more names, or where the old label already said so.
        return bool(o) and bool(n) and o[0] == n[0] and (o_etal or len(o) >= 3)
    return o == n


def label_changes(pre_text, post_text):
    """(substantive label changes, lines that differ outside link text) across a conversion.

    THE REVIEW A CONVERSION NEEDS. A changed label is how a registry error shows
    itself in an article: `Hanley and Lippman-Hand 1983` becoming `Hanley 1983`
    exposed a missing co-author, and `Gil and Sweeney` becoming `Sweeney and Gil`
    corrected the article. A change is substantive unless only `et al.`, a
    year suffix or diacritics differ. Any difference outside link text is
    reported separately, since conversion should touch nothing else.
    """
    def fold(x):
        return _fold(x).replace("\u2019", "'")

    def split_label(t):
        m = re.match(r"^(.*?)\s+(\d{4}|n\.d\.)([a-z]?)(?:, .*)?$", t)
        return (m.group(1), m.group(2)) if m else (t, None)
    pre_body, post_body = pre_text.split("\n## References\n")[0], post_text.split("\n## References\n")[0]
    seen, out = set(), []
    for (t1, a1), (t2, _a2) in zip(USE_RE.findall(pre_body), USE_RE.findall(post_body)):
        if t1 == t2 or (t1, t2) in seen:
            continue
        seen.add((t1, t2))
        n1, y1 = split_label(t1)
        n2, y2 = split_label(t2)
        if not (y1 == y2 and _same_people(n1, n2, fold)):
            out.append((a1, t1, t2))
    strip = re.compile(r"\[[^\]\n]+\]\[([a-z0-9_]+)\]")
    pl = strip.sub(r"[][\1]", pre_body).split("\n")
    ql = strip.sub(r"[][\1]", post_body).split("\n")
    other = [(i + 1, x, y) for i, (x, y) in enumerate(zip(pl, ql)) if x != y]
    if len(pl) != len(ql):
        other.append((min(len(pl), len(ql)) + 1, f"{len(pl)} lines", f"{len(ql)} lines"))
    # A NAME MUST STILL LINK TO WHAT IT LINKED TO. An alias DOI once came back from
    # Crossref as its primary and silently changed fifteen links, which only a
    # comparison of the definitions themselves can see.
    defs = re.compile(r"(?m)^\[([a-z0-9_]+)\]: (\S+)")
    unwrap = lambda t: t[1:-1] if t.startswith("<") and t.endswith(">") else t
    before = {a: unwrap(t).lower().rstrip(".") for a, t in defs.findall(pre_text)}
    after = {a: unwrap(t).lower().rstrip(".") for a, t in defs.findall(post_text)}
    import sources_resolve
    for a in sorted(set(before) & set(after)):
        if before[a] != after[a] and "oldid=" not in after[a]:
            # A LINK REPLACED BY THE DOI ITS OWN URL CARRIES, a JSTOR stable URL by
            # `10.2307/N` or an arXiv abstract by its arXiv DOI, still names the same
            # work. A DOI found any other way, by search or by PII, is reported.
            ident = sources_resolve.url_identifier(unwrap(before[a]))
            doi = None if not ident else ident[1] if ident[0] == "doi" else \
                sources_resolve.arxiv_doi(ident[1]).lower() if ident[0] == "arxiv" else None
            if doi and after[a] == f"https://doi.org/{doi}".lower():
                continue
            other.append((0, f"[{a}]: {before[a]}", f"[{a}]: {after[a]}"))
    return out, other


def check_article(path, records=None, venues=None):
    """Errors for a converted article file. An unconverted article returns none."""
    return check_text(open(path, encoding="utf-8").read(), records, venues, article=path)


def check_text(text, records=None, venues=None, posts_dir=POSTS, article=None):
    """Errors for a converted article's text. An unconverted article returns none."""
    if MARKER not in text:
        return []
    errs = []
    try:
        body, refs = split_article(text)
        want = generate(text, records, venues, posts_dir, article)
        if "## References\n" + refs != want:
            errs.append("References section differs from the database; run `python3 _lib/sources.py write`")
        for t, a, w in label_errors(text, records, posts_dir, article):
            errs.append(f"in-text [{t}][{a}] should read [{w}]")
    except SourceError as e:
        errs.append(str(e))
    return errs


def write_article(path, records=None, venues=None):
    text = open(path, encoding="utf-8").read()
    body, _ = split_article(text)
    new = body + generate(text, records, venues, article=path)
    with open(path, "w", encoding="utf-8") as f:
        f.write(new)
    return new


# ----------------------------------------------------------------------- CLI

def main(argv):
    if len(argv) < 2 or argv[1] not in ("validate", "render", "write", "check", "fix-labels", "diff-labels"):
        print(__doc__.split("Usage:")[1])
        return 2
    cmd, args = argv[1], argv[2:]
    try:
        if cmd == "validate":
            n, v = validate()
            print(f"{n} records and {v} venues valid")
            return 0
        if cmd == "render":
            sys.stdout.write(generate(open(args[0], encoding="utf-8").read(), article=args[0]))
            return 0
        if cmd == "diff-labels":
            changes, other = label_changes(open(args[0], encoding="utf-8").read(),
                                           open(args[1], encoding="utf-8").read())
            for a, t1, t2 in changes:
                print(f"  LABEL {a}: {t1!r} -> {t2!r}")
            for ln, x, y in other:
                print(f"  TEXT line {ln}: {x[:80]!r} -> {y[:80]!r}")
            print(f"{len(changes)} substantive label change(s), {len(other)} change(s) outside link text")
            return 0
        if cmd == "fix-labels":
            for p in args:
                new, changes = fix_labels(open(p, encoding="utf-8").read(), article=p)
                for old, rep_ in sorted(set(changes), key=str):
                    print(f"  {old!r} -> {rep_!r}" if rep_ else f"  CANNOT PLACE {old!r}, fix by hand")
                with open(p, "w", encoding="utf-8") as fh:
                    fh.write(new)
                print(f"{p}: {sum(1 for _o, n in changes if n)} label(s) set")
            return 0
        if cmd == "write":
            for p in args:
                write_article(p)
                print(f"wrote {p}")
            return 0
        bad = 0
        for p in args:
            for e in check_article(p):
                print(f"{p}: {e}")
                bad += 1
        print(f"{len(args)} checked, {bad} problem(s)")
        return 1 if bad else 0
    except SourceError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
